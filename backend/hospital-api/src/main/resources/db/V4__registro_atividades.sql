CREATE TABLE registro_atividade (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    funcionario_id  BIGINT REFERENCES funcionario(id) ON DELETE SET NULL,
    funcionario_nome VARCHAR(150) NOT NULL,
    funcionario_role VARCHAR(20)  NOT NULL,
    acao            VARCHAR(120) NOT NULL,
    entidade        VARCHAR(120) NOT NULL,
    detalhes        VARCHAR(500),
    data_hora       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_registro_atividade_funcionario_data
    ON registro_atividade (funcionario_id, data_hora DESC);

CREATE INDEX idx_registro_atividade_data
    ON registro_atividade (data_hora DESC);
